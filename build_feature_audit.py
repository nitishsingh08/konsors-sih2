"""
P1 -- Build the 141-feature implementation audit ledger.

Usage
-----
    python3 build_feature_audit.py [--outdir qc]

Writes
------
    qc/feature_audit_141.csv       full ledger, 141 rows, authoritative order
    qc/feature_audit_141.parquet   same, parquet (written if pandas available)
    qc/feature_status_summary.json  counts by status and by group
    qc/FEATURES_141.json            the frozen schema, machine readable
    qc/missing_features_by_phase.md the P3 work list, grouped by phase

Gate P1 (asserted at the end of this script):
    141 rows, unique features, no UNSET status, every row has a group,
    dataset and era window.
"""

from __future__ import annotations

import argparse
import csv
import json
from collections import Counter, defaultdict
from pathlib import Path

from feature_ledger import (
    DATASET,
    EXPECTED_GROUP_SIZES,
    FEATURES_141,
    GROUP_OF,
    GROUP_SAR,
    GROUP_ATMOSPHERIC,
    GROUP_SMOKE,
    LABEL_DERIVED_FEATURES,
    LEDGER_COLUMNS,
    N_FEATURES,
    NON_LEAK_FEATURES,
    S_COMPUTED,
    S_ERROR,
    S_HIST_NAN,
    S_MISSING_IMPL,
    S_MISSING_INPUT,
    S_RETIRED,
    S_UNVERIFIED,
    VALID_STATUSES,
    build_audit_records,
)

PHASE_TITLES = {
    "P0_recover_cell262": "P0 - Recover historical cell 262 (extract_fire_features)",
    "P2": "P2 - Verify with the 10-event forensic test",
    "P3a_industrial": "P3a - Industrial context (18) + event shape/geometry (6)",
    "P3b_quality": "P3b - Quality / uncertainty (8 features, from India_Firms)",
    "P3c_landcover": "P3c - Land cover / fuel (16 features)",
    "P3d_fwi": "P3d - Canadian Fire Weather Index (7 features)",
    "P3e_sar": "P3e - SAR / structural (7 features)",
    "P3f_smoke_atmospheric": "P3f - Smoke, atmospheric, lightning (16 features)",
    "P3g_recurrence": "P3g - Recurrence / inter-event gap (4 features)",
    "": "No further work required",
}


def write_csv(records, path: Path) -> None:
    with path.open("w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=LEDGER_COLUMNS)
        writer.writeheader()
        for record in records:
            row = dict(record)
            row["runtime_verified"] = "false"
            row["label_derived"] = "true" if row["label_derived"] else "false"
            writer.writerow(row)


def write_parquet(records, path: Path) -> bool:
    try:
        import pandas as pd
    except ImportError:
        print("  pandas not available - skipping parquet")
        return False
    frame = pd.DataFrame(records, columns=LEDGER_COLUMNS)
    try:
        frame.to_parquet(path, index=False)
    except (ImportError, ModuleNotFoundError) as exc:
        print(f"  no parquet engine ({exc.__class__.__name__}) - CSV only")
        return False
    return True


def write_summary(records, path: Path) -> dict:
    by_status = Counter(r["status"] for r in records)
    by_group = defaultdict(Counter)
    for r in records:
        by_group[r["group"]][r["status"]] += 1
    by_phase = defaultdict(list)
    for r in records:
        by_phase[r["phase"]].append(r["feature"])

    summary = {
        "n_features": N_FEATURES,
        "status_vocabulary": list(VALID_STATUSES),
        "counts_by_status": dict(sorted(by_status.items())),
        "counts_by_group": {g: dict(sorted(c.items())) for g, c in by_group.items()},
        "expected_group_sizes": EXPECTED_GROUP_SIZES,
        "label_derived_features": LABEL_DERIVED_FEATURES,
        "n_label_derived": len(LABEL_DERIVED_FEATURES),
        "n_non_leak": len(NON_LEAK_FEATURES),
        "features_by_phase": {k: v for k, v in sorted(by_phase.items())},
        "phase_titles": PHASE_TITLES,
        "open_phase_count": len([p for p in by_phase if p]),
        "runtime_verified_count": sum(1 for r in records if r["runtime_verified"]),
    }
    path.write_text(json.dumps(summary, indent=2), encoding="utf-8")
    return summary


def write_schema_json(path: Path) -> None:
    payload = {
        "n_features": N_FEATURES,
        "features": FEATURES_141,
        "group_of": GROUP_OF,
        "dataset_of": DATASET,
        "label_derived": LABEL_DERIVED_FEATURES,
        "non_leak": NON_LEAK_FEATURES,
        "source": "recovered notebook cells 233 and 246 (identical, 141/141 unique)",
        "retired_claim": "the earlier '131 feature' figure is an arithmetic error",
    }
    path.write_text(json.dumps(payload, indent=2), encoding="utf-8")


def write_worklist(records, path: Path) -> None:
    by_phase = defaultdict(list)
    for r in records:
        if r["status"] in (S_COMPUTED,):
            continue
        by_phase[r["phase"]].append(r)

    lines = [
        "# P3 work list -- features not yet computed",
        "",
        "Generated by `build_feature_audit.py`. Source of truth:",
        "`feature_audit_141.csv`.",
        "",
        f"Total features: **{len(records)}**",
        f"Computed historical: **{sum(1 for r in records if r['status'] == S_COMPUTED)}**",
        f"Still open: **{sum(1 for r in records if r['status'] != S_COMPUTED)}**",
        "",
    ]

    for phase in sorted(by_phase, key=lambda p: (p == "", p)):
        entries = by_phase[phase]
        lines.append(f"## {PHASE_TITLES.get(phase, phase)}")
        lines.append("")
        lines.append("| # | feature | group | status | dataset | era |")
        lines.append("| --- | --- | --- | --- | --- | --- |")
        for r in entries:
            lines.append(
                "| {i} | `{f}` | {g} | {s} | {d} | {a}..{b} |".format(
                    i=r["feature_index"],
                    f=r["feature"],
                    g=r["group"],
                    s=r["status"],
                    d=r["dataset"],
                    a=r["era_start"],
                    b=r["era_end"],
                )
            )
        lines.append("")
        if phase:
            lines.append(f"Subtotal: **{len(entries)} features**")
            lines.append("")

    missing_impl = sum(1 for r in records if r["status"] == S_MISSING_IMPL)
    lines.extend(
        [
            "## Leakage policy (declared before any training)",
            "",
            f"- `LABEL_DERIVED` ({len(LABEL_DERIVED_FEATURES)} features): all of "
            f"`{GROUP_OF[LABEL_DERIVED_FEATURES[0]]}`. Used for screening and "
            "interpretation only.",
            f"- `NON_LEAK` ({len(NON_LEAK_FEATURES)} features): the scientific "
            "model partition.",
            f"- {missing_impl} features currently have no executable "
            "implementation at all.",
            "",
        ]
    )
    path.write_text("\n".join(lines), encoding="utf-8")


def run(outdir: Path) -> dict:
    records = build_audit_records()

    outdir.mkdir(parents=True, exist_ok=True)

    csv_path = outdir / "feature_audit_141.csv"
    write_csv(records, csv_path)
    write_parquet(records, outdir / "feature_audit_141.parquet")

    summary = write_summary(records, outdir / "feature_status_summary.json")
    write_schema_json(outdir / "FEATURES_141.json")
    write_worklist(records, outdir / "missing_features_by_phase.md")

    # ---------------- Gate P1 ----------------
    assert len(records) == 141, f"expected 141 rows, got {len(records)}"
    assert len({r["feature"] for r in records}) == 141, "duplicate features"
    assert [r["feature"] for r in records] == FEATURES_141, "order drift"
    assert all(r["status"] in VALID_STATUSES for r in records), "invalid status"
    assert all(r["group"] and r["dataset"] and r["era_start"] for r in records)
    assert not any(r["status"] in ("UNSET", "", None) for r in records)

    print(f"Ledger written to {outdir}")
    print(f"  rows: {len(records)}")
    print("  counts by status:")
    for status, count in summary["counts_by_status"].items():
        print(f"    {status:<24} {count:>4}")
    print("  counts by group:")
    for group, counts in summary["counts_by_group"].items():
        detail = ", ".join(f"{k}={v}" for k, v in counts.items())
        print(f"    {group:<24} {sum(counts.values()):>4}  ({detail})")
    print("  open work items by phase:")
    for phase, features in summary["features_by_phase"].items():
        if phase:
            print(f"    {PHASE_TITLES.get(phase, phase)}: {len(features)}")
    print()
    print("GATE P1 PASSED")
    return summary


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--outdir", default="qc", type=Path)
    args = parser.parse_args()
    run(args.outdir)


if __name__ == "__main__":
    main()